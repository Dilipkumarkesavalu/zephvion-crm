-- Phase 1: saved list views, personal or shared with the team
-- Saved views ---------------------------------------------------------------

create table public.saved_views (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    sales_id bigint not null default public.current_sales_id(),
    resource text not null,
    name text not null,
    filter jsonb not null default '{}'::jsonb,
    is_shared boolean not null default false,
    constraint saved_views_resource_check check (resource in ('contacts', 'companies', 'deals', 'invoices')),
    constraint saved_views_name_check check (char_length(name) between 1 and 60)
);

alter table public.saved_views
    add constraint saved_views_sales_id_fkey foreign key (sales_id) references public.sales(id) on delete cascade;

create index saved_views_resource_idx on public.saved_views using btree (resource, sales_id);


alter table public.saved_views enable row level security;
create policy "Read own and shared views" on public.saved_views for select to authenticated using (sales_id = public.current_sales_id() or is_shared);
create policy "Create own views" on public.saved_views for insert to authenticated with check (sales_id = public.current_sales_id());
create policy "Update own views" on public.saved_views for update to authenticated using (sales_id = public.current_sales_id()) with check (sales_id = public.current_sales_id());
create policy "Delete own views" on public.saved_views for delete to authenticated using (sales_id = public.current_sales_id());


grant select, insert, update, delete on table public.saved_views to authenticated;
grant all on table public.saved_views to service_role;
grant all on sequence public.saved_views_id_seq to service_role;

