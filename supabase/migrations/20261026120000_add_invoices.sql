-- Quotes & invoices
create table public.invoices (
    id bigint generated by default as identity primary key,
    type text not null check (type in ('quote', 'invoice')),
    number text not null unique,
    status text not null default 'draft',
    company_id bigint not null,
    contact_id bigint,
    deal_id bigint,
    sales_id bigint,
    issue_date date not null default current_date,
    due_date date,
    tax_mode text not null default 'intra' check (tax_mode in ('intra', 'inter')),
    items jsonb not null default '[]'::jsonb,
    notes text,
    subtotal numeric(14, 2) not null default 0,
    tax_total numeric(14, 2) not null default 0,
    total numeric(14, 2) not null default 0,
    source_quote_id bigint,
    paid_at timestamp with time zone,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now()
);

alter table public.invoices
    add constraint invoices_company_id_fkey foreign key (company_id) references public.companies(id) on update cascade on delete cascade;

alter table public.invoices
    add constraint invoices_contact_id_fkey foreign key (contact_id) references public.contacts(id) on update cascade on delete set null;

alter table public.invoices
    add constraint invoices_deal_id_fkey foreign key (deal_id) references public.deals(id) on update cascade on delete set null;

alter table public.invoices
    add constraint invoices_sales_id_fkey foreign key (sales_id) references public.sales(id);

alter table public.invoices
    add constraint invoices_source_quote_id_fkey foreign key (source_quote_id) references public.invoices(id) on delete set null;

create index invoices_company_id_idx on public.invoices using btree (company_id);
create index invoices_deal_id_idx on public.invoices using btree (deal_id);

create or replace trigger set_invoice_sales_id_trigger
    before insert on public.invoices
    for each row execute function public.set_sales_id_default();

alter table public.invoices enable row level security;
create policy "Enable read access for authenticated users" on public.invoices for select to authenticated using (true);
create policy "Enable insert for authenticated users only" on public.invoices for insert to authenticated with check (true);
create policy "Enable update for authenticated users only" on public.invoices for update to authenticated using (true) with check (true);
create policy "Invoices Delete Policy" on public.invoices for delete to authenticated using (true);
grant all on table public.invoices to anon;
grant all on table public.invoices to authenticated;
grant all on table public.invoices to service_role;

grant all on sequence public.invoices_id_seq to anon;
grant all on sequence public.invoices_id_seq to authenticated;
grant all on sequence public.invoices_id_seq to service_role;
