-- AI assistant: one row per request, for cost tracking and a daily limit
-- per person. Written by the ai_assistant function only.

create table public.ai_requests (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    sales_id bigint not null,
    action text not null,
    resource text,
    record_id bigint,
    model text,
    input_tokens integer not null default 0,
    output_tokens integer not null default 0,
    outcome text not null default 'ok',
    constraint ai_requests_action_check check (action in ('summarize_company', 'draft_email', 'ask'))
);

alter table public.ai_requests
    add constraint ai_requests_sales_id_fkey foreign key (sales_id) references public.sales(id) on delete cascade;

create index ai_requests_sales_idx on public.ai_requests using btree (sales_id, created_at desc);

-- People see their own usage; admins see everyone's
alter table public.ai_requests enable row level security;
create policy "Read own AI usage" on public.ai_requests for select to authenticated using (sales_id = public.current_sales_id() or public.is_admin());

grant select on table public.ai_requests to authenticated;
grant all on table public.ai_requests to service_role;
grant all on sequence public.ai_requests_id_seq to service_role;
