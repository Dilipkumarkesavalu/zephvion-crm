-- Client portal: a secret link per client, used through the client_portal
-- function. Only a SHA-256 fingerprint of each link's token is stored.

create table public.portal_access (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    company_id bigint not null,
    token_hash text not null,
    is_active boolean not null default true,
    sales_id bigint default public.current_sales_id(),
    last_used_at timestamp with time zone,
    constraint portal_access_token_hash_key unique (token_hash),
    constraint portal_access_token_hash_check check (token_hash ~ '^[0-9a-f]{64}$')
);

alter table public.portal_access
    add constraint portal_access_company_id_fkey foreign key (company_id) references public.companies(id) on delete cascade;
alter table public.portal_access
    add constraint portal_access_sales_id_fkey foreign key (sales_id) references public.sales(id) on delete set null;

-- One working link per client at a time
create unique index portal_access_active_company_idx on public.portal_access using btree (company_id) where is_active;

-- Replies clients send through the portal
alter table public.ticket_comments
    add column is_from_client boolean not null default false;

-- A client's own message is not the team's first response
CREATE OR REPLACE FUNCTION "public"."mark_ticket_responded"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if not new.is_internal and not new.is_from_client then
    update public.tickets
    set first_responded_at = coalesce(first_responded_at, new.created_at)
    where id = new.ticket_id and first_responded_at is null;
  end if;
  update public.tickets set updated_at = now() where id = new.ticket_id;
  return new;
end;
$$;

create or replace trigger audit_portal_access after insert or update or delete on public.portal_access
    for each row execute function public.write_audit_log();

-- Staff manage links for clients they can see; the portal itself reads
-- through the client_portal function with the service role
alter table public.portal_access enable row level security;
create policy "Read portal links of visible clients" on public.portal_access for select to authenticated using (exists (select 1 from public.companies c where c.id = portal_access.company_id));
create policy "Create portal links for visible clients" on public.portal_access for insert to authenticated with check (exists (select 1 from public.companies c where c.id = portal_access.company_id));
create policy "Update portal links of visible clients" on public.portal_access for update to authenticated using (exists (select 1 from public.companies c where c.id = portal_access.company_id)) with check (exists (select 1 from public.companies c where c.id = portal_access.company_id));

grant select, insert, update on table public.portal_access to authenticated;
grant all on table public.portal_access to service_role;
grant all on sequence public.portal_access_id_seq to service_role;
