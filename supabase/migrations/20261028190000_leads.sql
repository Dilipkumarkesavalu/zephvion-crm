-- Phase 2: lead inbox with scoring, auto-assignment and a first-response SLA

-- Leads ----------------------------------------------------------------------

create table public.leads (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    first_name text not null,
    last_name text,
    email text,
    phone text,
    company_name text,
    service text,
    budget numeric(14, 2),
    message text,
    source text not null default 'manual',
    utm_source text,
    utm_campaign text,
    status text not null default 'new',
    sales_id bigint,
    score integer not null default 0,
    first_response_due timestamp with time zone,
    first_responded_at timestamp with time zone,
    disqualify_reason text,
    converted_contact_id bigint,
    converted_company_id bigint,
    converted_deal_id bigint,
    constraint leads_source_check check (source in ('website', 'whatsapp', 'email', 'referral', 'linkedin', 'event', 'import', 'manual', 'other')),
    constraint leads_status_check check (status in ('new', 'contacted', 'qualified', 'disqualified', 'converted')),
    constraint leads_name_check check (char_length(first_name) between 1 and 120),
    constraint leads_message_check check (message is null or char_length(message) <= 5000)
);

alter table public.leads
    add constraint leads_sales_id_fkey foreign key (sales_id) references public.sales(id) on delete set null;
alter table public.leads
    add constraint leads_converted_contact_id_fkey foreign key (converted_contact_id) references public.contacts(id) on delete set null;
alter table public.leads
    add constraint leads_converted_company_id_fkey foreign key (converted_company_id) references public.companies(id) on delete set null;
alter table public.leads
    add constraint leads_converted_deal_id_fkey foreign key (converted_deal_id) references public.deals(id) on delete set null;

create index leads_status_idx on public.leads using btree (status, created_at desc);
create index leads_sales_id_idx on public.leads using btree (sales_id);
create index leads_email_idx on public.leads using btree (lower(email));

-- Same rules as src/components/zephvion-crm/leads/leadScore.ts
CREATE OR REPLACE FUNCTION "public"."lead_score"("lead" "public"."leads") RETURNS integer
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
  select least(100,
    case
      when coalesce(lead.budget, 0) >= 500000 then 40
      when coalesce(lead.budget, 0) >= 200000 then 30
      when coalesce(lead.budget, 0) >= 50000 then 20
      when coalesce(lead.budget, 0) > 0 then 10
      else 0
    end
    + case when coalesce(trim(lead.company_name), '') <> '' then 15 else 0 end
    + case when coalesce(trim(lead.phone), '') <> '' then 10 else 0 end
    + case when coalesce(trim(lead.email), '') <> '' then 5 else 0 end
    + case lead.source
        when 'referral' then 20
        when 'website' then 15
        when 'whatsapp' then 15
        when 'email' then 10
        when 'linkedin' then 10
        when 'event' then 10
        else 5
      end
    + case when char_length(coalesce(lead.message, '')) >= 40 then 10 else 0 end
  )
$$;

-- Active member of the sales department with the fewest open leads
CREATE OR REPLACE FUNCTION "public"."pick_lead_owner"() RETURNS bigint
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
  select s.id
  from public.sales s
  join public.departments d on d.id = s.department_id
  where d.name = 'Sales and Business Development' and not s.disabled
  order by (
    select count(*) from public.leads l
    where l.sales_id = s.id and l.status in ('new', 'contacted', 'qualified')
  ), s.id
  limit 1
$$;

CREATE OR REPLACE FUNCTION "public"."prepare_lead"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  new.updated_at := now();
  new.score := public.lead_score(new);
  if tg_op = 'INSERT' then
    if new.sales_id is null then
      new.sales_id := public.pick_lead_owner();
    end if;
    -- Two hours to make first contact
    new.first_response_due := coalesce(new.first_response_due, new.created_at + interval '2 hours');
  end if;
  if new.status <> 'new' and new.first_responded_at is null then
    new.first_responded_at := now();
  end if;
  return new;
end;
$$;

CREATE OR REPLACE FUNCTION "public"."notify_assignment"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  actor bigint := public.current_sales_id();
  row_data jsonb := to_jsonb(new);
  record_title text;
begin
  if new.sales_id is null
    or (tg_op = 'UPDATE' and new.sales_id is not distinct from old.sales_id)
    or new.sales_id is not distinct from actor then
    return new;
  end if;

  record_title := case tg_table_name
    when 'contacts' then trim(concat_ws(' ', row_data ->> 'first_name', row_data ->> 'last_name'))
    when 'leads' then trim(concat_ws(' ', row_data ->> 'first_name', row_data ->> 'last_name', nullif('· ' || coalesce(row_data ->> 'company_name', ''), '· ')))
    when 'tasks' then row_data ->> 'text'
    else row_data ->> 'name'
  end;

  insert into public.notifications (recipient_sales_id, actor_sales_id, type, resource, record_id, title)
  values (
    new.sales_id,
    actor,
    tg_table_name || '_assigned',
    tg_table_name,
    (row_data ->> 'id')::bigint,
    left(coalesce(nullif(record_title, ''), 'Untitled'), 200)
  );
  return new;
end;
$$;

create or replace trigger prepare_lead before insert or update on public.leads
    for each row execute function public.prepare_lead();
create or replace trigger audit_leads after insert or update or delete on public.leads
    for each row execute function public.write_audit_log();
create or replace trigger notify_lead_assignment after insert or update of sales_id on public.leads
    for each row execute function public.notify_assignment();

