create or replace trigger audit_departments after insert or update or delete on public.departments for each row execute function public.write_audit_log();

-- Notifications -------------------------------------------------------------

create table public.notifications (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    recipient_sales_id bigint not null,
    actor_sales_id bigint,
    type text not null,
    resource text not null,
    record_id bigint not null,
    title text not null,
    read_at timestamp with time zone
);

alter table public.notifications
    add constraint notifications_recipient_sales_id_fkey foreign key (recipient_sales_id) references public.sales(id) on delete cascade;
alter table public.notifications
    add constraint notifications_actor_sales_id_fkey foreign key (actor_sales_id) references public.sales(id) on delete set null;

create index notifications_recipient_idx on public.notifications using btree (recipient_sales_id, created_at desc);

CREATE OR REPLACE FUNCTION "public"."notify_assignment"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  actor bigint := public.current_sales_id();
  row_data jsonb := to_jsonb(new);
  record_title text;
begin
  if new.sales_id is null
    or (tg_op = 'UPDATE' and new.sales_id is not distinct from old.sales_id)
    or new.sales_id is not distinct from actor then
    return new;
  end if;

  record_title := case tg_table_name
    when 'contacts' then trim(concat_ws(' ', row_data ->> 'first_name', row_data ->> 'last_name'))
    when 'tasks' then row_data ->> 'text'
    else row_data ->> 'name'
  end;

  insert into public.notifications (recipient_sales_id, actor_sales_id, type, resource, record_id, title)
  values (
    new.sales_id,
    actor,
    tg_table_name || '_assigned',
    tg_table_name,
    (row_data ->> 'id')::bigint,
    left(coalesce(nullif(record_title, ''), 'Untitled'), 200)
  );
  return new;
end;
$$;

create or replace trigger notify_task_assignment after insert or update of sales_id on public.tasks for each row execute function public.notify_assignment();
create or replace trigger notify_deal_assignment after insert or update of sales_id on public.deals for each row execute function public.notify_assignment();
create or replace trigger notify_contact_assignment after insert or update of sales_id on public.contacts for each row execute function public.notify_assignment();
create or replace trigger notify_company_assignment after insert or update of sales_id on public.companies for each row execute function public.notify_assignment();

-- Policies ------------------------------------------------------------------

alter table public.departments enable row level security;
alter table public.audit_log enable row level security;
alter table public.notifications enable row level security;

create policy "Enable read access for authenticated users" on public.departments for select to authenticated using (true);
create policy "Enable insert for admins" on public.departments for insert to authenticated with check (public.is_admin());
create policy "Enable update for admins" on public.departments for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "Enable delete for admins" on public.departments for delete to authenticated using (public.is_admin());

create policy "Enable read access for admins" on public.audit_log for select to authenticated using (public.is_admin());

create policy "Recipients read their notifications" on public.notifications for select to authenticated using (recipient_sales_id = public.current_sales_id());
create policy "Recipients update their notifications" on public.notifications for update to authenticated using (recipient_sales_id = public.current_sales_id()) with check (recipient_sales_id = public.current_sales_id());
create policy "Recipients delete their notifications" on public.notifications for delete to authenticated using (recipient_sales_id = public.current_sales_id());

