-- Invoice columns -------------------------------------------------------------

alter table public.invoices
    add column amount_paid numeric(14, 2) not null default 0,
    add column recurrence text not null default 'none',
    add column next_issue_date date,
    add column recurring_parent_id bigint,
    add column payment_link_url text,
    add column payment_link_id text;

alter table public.invoices
    add constraint invoices_recurrence_check check (recurrence in ('none', 'monthly', 'quarterly', 'yearly'));
alter table public.invoices
    add constraint invoices_recurring_parent_id_fkey foreign key (recurring_parent_id) references public.invoices(id) on delete set null;

-- Invoices already marked paid count as fully paid
update public.invoices set amount_paid = total where type = 'invoice' and status = 'paid';

-- Payments ---------------------------------------------------------------------

create table public.invoice_payments (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    invoice_id bigint not null,
    amount numeric(14, 2) not null,
    tds_amount numeric(14, 2) not null default 0,
    paid_on date not null default current_date,
    method text not null default 'bank_transfer',
    reference text,
    notes text,
    sales_id bigint default public.current_sales_id(),
    external_id text unique,
    constraint invoice_payments_amount_check check (amount >= 0),
    constraint invoice_payments_tds_check check (tds_amount >= 0),
    constraint invoice_payments_total_check check (amount + tds_amount > 0),
    constraint invoice_payments_method_check check (method in ('bank_transfer', 'upi', 'razorpay', 'cheque', 'cash', 'other'))
);

alter table public.invoice_payments
    add constraint invoice_payments_invoice_id_fkey foreign key (invoice_id) references public.invoices(id) on delete cascade;
alter table public.invoice_payments
    add constraint invoice_payments_sales_id_fkey foreign key (sales_id) references public.sales(id) on delete set null;

create index invoice_payments_invoice_id_idx on public.invoice_payments using btree (invoice_id);

-- Reminders sent, one per stage per invoice ------------------------------------

create table public.invoice_reminders (
    id bigint generated by default as identity primary key,
    sent_at timestamp with time zone not null default now(),
    invoice_id bigint not null,
    kind text not null,
    sent_to text not null,
    sales_id bigint,
    constraint invoice_reminders_kind_check check (kind in ('before_due', 'due', 'overdue_7', 'overdue_14', 'overdue_30', 'manual'))
);

alter table public.invoice_reminders
    add constraint invoice_reminders_invoice_id_fkey foreign key (invoice_id) references public.invoices(id) on delete cascade;

create index invoice_reminders_invoice_id_idx on public.invoice_reminders using btree (invoice_id);
create unique index invoice_reminders_stage_idx on public.invoice_reminders using btree (invoice_id, kind) where kind <> 'manual';

-- Keep amount_paid and the paid status in step with the payments ----------------

CREATE OR REPLACE FUNCTION "public"."refresh_invoice_payments"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  target_id bigint := coalesce(new.invoice_id, old.invoice_id);
  settled numeric(14, 2);
  last_paid date;
begin
  select coalesce(sum(p.amount + p.tds_amount), 0), max(p.paid_on)
    into settled, last_paid
    from public.invoice_payments p
    where p.invoice_id = target_id;

  update public.invoices i
  set amount_paid = settled,
      status = case
        when i.type = 'invoice' and i.status in ('sent', 'paid') and settled >= i.total then 'paid'
        when i.type = 'invoice' and i.status = 'paid' and settled < i.total then 'sent'
        else i.status
      end,
      paid_at = case
        when i.type = 'invoice' and settled >= i.total then coalesce(i.paid_at, last_paid::timestamp with time zone)
        when i.type = 'invoice' and i.status = 'paid' and settled < i.total then null
        else i.paid_at
      end,
      updated_at = now()
  where i.id = target_id;
  return null;
end;
$$;

create or replace trigger refresh_invoice_payments after insert or update or delete on public.invoice_payments
    for each row execute function public.refresh_invoice_payments();
create or replace trigger audit_invoice_payments after insert or update or delete on public.invoice_payments
    for each row execute function public.write_audit_log();

-- Recurring invoices ------------------------------------------------------------

-- Same series as getNextDocumentNumber() in invoiceModel.ts: INV-2026-0001
CREATE OR REPLACE FUNCTION "public"."next_invoice_number"("issued_on" date) RETURNS text
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
  select 'INV-' || extract(year from issued_on)::int || '-' || lpad((
    coalesce(max(nullif(regexp_replace(substr(i.number, 10), '\D', '', 'g'), '')::int), 0) + 1
  )::text, 4, '0')
  from public.invoices i
  where i.number like 'INV-' || extract(year from issued_on)::int || '-%'
$$;

-- Drafts the next invoice for every recurring invoice that is due, so the
-- team can check and send it. Catches up on missed runs, at most 12 at a time.
CREATE OR REPLACE FUNCTION "public"."generate_recurring_invoices"() RETURNS integer
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  template public.invoices;
  step interval;
  payment_days integer;
  created integer := 0;
  rounds integer;
begin
  for template in
    select * from public.invoices
    where type = 'invoice' and recurrence <> 'none' and status <> 'cancelled'
      and next_issue_date is not null and next_issue_date <= current_date
    for update
  loop
    step := case template.recurrence
      when 'monthly' then interval '1 month'
      when 'quarterly' then interval '3 months'
      else interval '1 year'
    end;
    payment_days := coalesce(template.due_date - template.issue_date, 15);
    rounds := 0;
    while template.next_issue_date <= current_date and rounds < 12 loop
      insert into public.invoices (
        type, number, status, company_id, contact_id, deal_id, sales_id,
        issue_date, due_date, tax_mode, items, notes, subtotal, tax_total, total,
        recurring_parent_id
      ) values (
        'invoice', public.next_invoice_number(template.next_issue_date), 'draft',
        template.company_id, template.contact_id, template.deal_id, template.sales_id,
        template.next_issue_date, template.next_issue_date + payment_days,
        template.tax_mode, template.items, template.notes,
        template.subtotal, template.tax_total, template.total, template.id
      );
      template.next_issue_date := (template.next_issue_date + step)::date;
      rounds := rounds + 1;
      created := created + 1;
    end loop;
    update public.invoices set next_issue_date = template.next_issue_date where id = template.id;
  end loop;
  return created;
end;
$$;

-- Daily at 09:00 India time
create extension if not exists pg_cron with schema pg_catalog;
grant usage on schema cron to postgres;
select cron.schedule('generate-recurring-invoices', '30 3 * * *', $$select public.generate_recurring_invoices()$$);

