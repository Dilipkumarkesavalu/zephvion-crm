-- Delivery: projects from won deals, milestones billed as invoices, timesheets

-- Projects ---------------------------------------------------------------------

create table public.projects (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    name text not null,
    company_id bigint not null,
    deal_id bigint,
    sales_id bigint default public.current_sales_id(),
    status text not null default 'planning',
    start_date date,
    due_date date,
    budget numeric(14, 2) not null default 0,
    budget_hours numeric(8, 2) not null default 0,
    description text,
    constraint projects_name_check check (char_length(name) between 1 and 200),
    constraint projects_status_check check (status in ('planning', 'active', 'on_hold', 'completed', 'cancelled')),
    constraint projects_budget_check check (budget >= 0 and budget_hours >= 0)
);

alter table public.projects
    add constraint projects_company_id_fkey foreign key (company_id) references public.companies(id) on delete cascade;
alter table public.projects
    add constraint projects_deal_id_fkey foreign key (deal_id) references public.deals(id) on delete set null;
alter table public.projects
    add constraint projects_sales_id_fkey foreign key (sales_id) references public.sales(id) on delete set null;

create index projects_company_id_idx on public.projects using btree (company_id);
create unique index projects_deal_id_idx on public.projects using btree (deal_id) where deal_id is not null;

-- Milestones ---------------------------------------------------------------------

create table public.project_milestones (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    project_id bigint not null,
    name text not null,
    due_date date,
    amount numeric(14, 2) not null default 0,
    status text not null default 'pending',
    completed_at timestamp with time zone,
    position integer not null default 0,
    constraint project_milestones_name_check check (char_length(name) between 1 and 200),
    constraint project_milestones_status_check check (status in ('pending', 'in_progress', 'done')),
    constraint project_milestones_amount_check check (amount >= 0)
);

alter table public.project_milestones
    add constraint project_milestones_project_id_fkey foreign key (project_id) references public.projects(id) on delete cascade;

create index project_milestones_project_id_idx on public.project_milestones using btree (project_id, position);

-- Time entries -------------------------------------------------------------------

create table public.time_entries (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    project_id bigint not null,
    milestone_id bigint,
    sales_id bigint not null default public.current_sales_id(),
    spent_on date not null default current_date,
    hours numeric(5, 2) not null,
    description text,
    billable boolean not null default true,
    constraint time_entries_hours_check check (hours > 0 and hours <= 24),
    constraint time_entries_description_check check (description is null or char_length(description) <= 1000)
);

alter table public.time_entries
    add constraint time_entries_project_id_fkey foreign key (project_id) references public.projects(id) on delete cascade;
alter table public.time_entries
    add constraint time_entries_milestone_id_fkey foreign key (milestone_id) references public.project_milestones(id) on delete set null;
alter table public.time_entries
    add constraint time_entries_sales_id_fkey foreign key (sales_id) references public.sales(id) on delete cascade;

create index time_entries_project_id_idx on public.time_entries using btree (project_id, spent_on desc);
create index time_entries_sales_id_idx on public.time_entries using btree (sales_id, spent_on desc);

-- Invoices billed for a project or one of its milestones -------------------------

alter table public.invoices
    add column project_id bigint,
    add column milestone_id bigint;
alter table public.invoices
    add constraint invoices_project_id_fkey foreign key (project_id) references public.projects(id) on delete set null;
alter table public.invoices
    add constraint invoices_milestone_id_fkey foreign key (milestone_id) references public.project_milestones(id) on delete set null;
create index invoices_project_id_idx on public.invoices using btree (project_id);

-- Bookkeeping ----------------------------------------------------------------------

CREATE OR REPLACE FUNCTION "public"."touch_project"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- Stamps when a milestone is done, and clears it if reopened
CREATE OR REPLACE FUNCTION "public"."stamp_milestone_completion"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
begin
  if new.status = 'done' and new.completed_at is null then
    new.completed_at := now();
  elsif new.status <> 'done' then
    new.completed_at := null;
  end if;
  return new;
end;
$$;

create or replace trigger touch_project before update on public.projects
    for each row execute function public.touch_project();
create or replace trigger stamp_milestone_completion before insert or update on public.project_milestones
    for each row execute function public.stamp_milestone_completion();
create or replace trigger audit_projects after insert or update or delete on public.projects
    for each row execute function public.write_audit_log();
create or replace trigger notify_project_assignment after insert or update of sales_id on public.projects
    for each row execute function public.notify_assignment();

-- Access ---------------------------------------------------------------------------

alter table public.projects enable row level security;
create policy "Read visible projects" on public.projects for select to authenticated using (public.can_see_owner(sales_id) or exists (select 1 from public.companies c where c.id = projects.company_id));
create policy "Create projects" on public.projects for insert to authenticated with check (true);
create policy "Update visible projects" on public.projects for update to authenticated using (public.can_see_owner(sales_id) or exists (select 1 from public.companies c where c.id = projects.company_id)) with check (true);
create policy "Delete visible projects" on public.projects for delete to authenticated using (public.can_see_owner(sales_id) or exists (select 1 from public.companies c where c.id = projects.company_id));

alter table public.project_milestones enable row level security;
create policy "Milestones of visible projects" on public.project_milestones for all to authenticated using (exists (select 1 from public.projects p where p.id = project_milestones.project_id)) with check (exists (select 1 from public.projects p where p.id = project_milestones.project_id));

-- Everyone on a visible project sees its time; people change only their own
-- entries, admins any
alter table public.time_entries enable row level security;
create policy "Read time on visible projects" on public.time_entries for select to authenticated using (exists (select 1 from public.projects p where p.id = time_entries.project_id));
create policy "Log own time" on public.time_entries for insert to authenticated with check (sales_id = public.current_sales_id() and exists (select 1 from public.projects p where p.id = time_entries.project_id));
create policy "Edit own time" on public.time_entries for update to authenticated using (sales_id = public.current_sales_id() or public.is_admin()) with check (sales_id = public.current_sales_id() or public.is_admin());
create policy "Delete own time" on public.time_entries for delete to authenticated using (sales_id = public.current_sales_id() or public.is_admin());

grant select, insert, update, delete on table public.projects to authenticated;
grant select, insert, update, delete on table public.project_milestones to authenticated;
grant select, insert, update, delete on table public.time_entries to authenticated;
grant all on table public.projects to service_role;
grant all on table public.project_milestones to service_role;
grant all on table public.time_entries to service_role;
grant all on sequence public.projects_id_seq to service_role;
grant all on sequence public.project_milestones_id_seq to service_role;
grant all on sequence public.time_entries_id_seq to service_role;

-- Saved views cover projects too
alter table public.saved_views drop constraint saved_views_resource_check;
alter table public.saved_views add constraint saved_views_resource_check check (resource in ('leads', 'contacts', 'companies', 'deals', 'invoices', 'projects'));
