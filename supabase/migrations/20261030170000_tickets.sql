-- Support desk: tickets with priorities, response/resolution deadlines,
-- auto-assignment to the support team and a comment thread

create sequence public.ticket_number_seq;

create table public.tickets (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    number text not null default ('TKT-' || lpad(nextval('public.ticket_number_seq')::text, 4, '0')),
    subject text not null,
    description text,
    company_id bigint,
    contact_id bigint,
    project_id bigint,
    sales_id bigint,
    status text not null default 'open',
    priority text not null default 'normal',
    channel text not null default 'email',
    first_response_due timestamp with time zone,
    resolve_due timestamp with time zone,
    first_responded_at timestamp with time zone,
    resolved_at timestamp with time zone,
    constraint tickets_number_key unique (number),
    constraint tickets_subject_check check (char_length(subject) between 1 and 200),
    constraint tickets_description_check check (description is null or char_length(description) <= 20000),
    constraint tickets_status_check check (status in ('open', 'in_progress', 'waiting_client', 'resolved', 'closed')),
    constraint tickets_priority_check check (priority in ('low', 'normal', 'high', 'urgent')),
    constraint tickets_channel_check check (channel in ('email', 'phone', 'whatsapp', 'portal', 'other'))
);

